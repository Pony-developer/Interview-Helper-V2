/**
 * Builds supabase/seed.sql from the authored content in /content.
 *   npm run seed:build            → validate + write supabase/seed.sql
 *   npm run db:push    → supabase db push --remote --include-seed (applies to the linked project)
 * The SQL is idempotent: rows are upserted by slug.
 */
import { writeFileSync } from "node:fs";
import { courses as catalogCourses } from "@content/courses";
import { loadCourseModules } from "@/lib/content/course-loader";
import { deriveCourseTasks, type CourseTask } from "@/lib/content/course-tasks";
import { lectureForTask, loadContent } from "@/lib/content/loader";
import { countTests, type PracticePayload } from "@/lib/playground/frameworks";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const j = (v: unknown) => (v == null ? "null::jsonb" : `${q(JSON.stringify(v))}::jsonb`);
const arr = (v: string[]) => (v.length ? `array[${v.map(q).join(", ")}]::text[]` : "'{}'::text[]");
// Multi-line text goes in as a JSON string so that every row stays on one line (see seed-remote.mjs).
const text = (v: string | null | undefined) => (v == null ? "null::text" : `(${j(v)} #>> '{}')`);
const refSlug = (ref: string | { slug: string }) => (typeof ref === "string" ? ref : ref.slug);

async function main() {
  const { skills, lectures, tasks, errors } = await loadContent();
  if (errors.length) {
    console.error(`Content validation failed (${errors.length}):\n - ${errors.join("\n - ")}`);
    process.exit(1);
  }

  // Courses are loaded up front: their quizzes and practices can also become interview tasks.
  const { courses: loadedCourses, errors: courseErrors } = loadCourseModules();
  if (courseErrors.length) {
    console.error(`Course validation failed (${courseErrors.length}):\n - ${courseErrors.join("\n - ")}`);
    process.exit(1);
  }
  const derived = deriveCourseTasks(loadedCourses, new Set(skills.map((s) => s.slug)));
  const authoredSlugs = new Set(tasks.map((t) => t.slug));
  for (const t of derived.tasks)
    if (authoredSlugs.has(t.slug)) derived.errors.push(`course-tasks: ${t.slug} is also a slug in content/tasks`);
  if (derived.errors.length) {
    console.error(`Course task rules failed (${derived.errors.length}):\n - ${derived.errors.join("\n - ")}`);
    process.exit(1);
  }
  const courseTasks = derived.tasks;
  const allTaskSlugs = [...tasks.map((t) => t.slug), ...courseTasks.map((t) => t.slug)];

  const skillsWithContent = new Set<string>();
  for (const t of [...tasks, ...courseTasks]) for (const ref of t.skills) skillsWithContent.add(refSlug(ref));

  const out: string[] = [];
  out.push("-- Generated by scripts/build-seed.ts. Do not edit by hand.");
  out.push("begin;", "");

  // Skills
  // Rows edited in the admin panel (source = 'admin') are never overwritten by the seed.
  out.push("insert into public.skills as cur (slug, name, category, aliases, description, codeable, has_content, popularity) values");
  out.push(
    skills
      .map(
        (s) =>
          `  (${q(s.slug)}, ${q(s.name)}, ${q(s.category)}, ${arr([...s.aliases, ...s.caseSensitiveAliases])}, ${j(
            s.description ?? {},
          )}, ${s.codeable}, ${skillsWithContent.has(s.slug)}, ${s.popularity})`,
      )
      .join(",\n"),
  );
  out.push(
    "on conflict (slug) do update set name = excluded.name, category = excluded.category, aliases = excluded.aliases,",
    "  description = excluded.description, codeable = excluded.codeable, has_content = excluded.has_content, popularity = excluded.popularity",
    "where cur.source = 'seed';",
    "",
  );

  // Lectures
  if (lectures.length) {
    out.push("insert into public.lectures as cur (slug, skill_id, title, summary, body, reading_minutes, updated_at)");
    out.push("select v.slug, s.id, v.title, v.summary, v.body, v.reading_minutes, now() from (values");
    out.push(
      lectures
        .map((l) => `  (${q(l.slug)}, ${q(l.skill)}, ${j(l.title)}, ${j(l.summary)}, ${j(l.body)}, ${l.readingMinutes})`)
        .join(",\n"),
    );
    out.push(") as v(slug, skill_slug, title, summary, body, reading_minutes)");
    out.push("join public.skills s on s.slug = v.skill_slug");
    out.push(
      "on conflict (slug) do update set skill_id = excluded.skill_id, title = excluded.title, summary = excluded.summary,",
      "  body = excluded.body, reading_minutes = excluded.reading_minutes, updated_at = now()",
      "where cur.source = 'seed';",
      "",
    );
  }

  // Tasks
  if (tasks.length) {
    out.push("insert into public.tasks as cur (slug, kind, complexity, est_seconds, title, prompt, lecture_id, quiz, practice, published, updated_at)");
    out.push("select v.slug, v.kind::public.task_kind, v.complexity, v.est_seconds, v.title, v.prompt, l.id, v.quiz, v.practice, true, now() from (values");
    out.push(
      tasks
        .map((t) => {
          const lecture = lectureForTask(t, lectures);
          const quiz =
            t.kind === "quiz"
              ? { mode: t.mode, code: t.code, codeLanguage: t.codeLanguage, options: t.options }
              : null;
          const practice: PracticePayload | null =
            t.kind === "practice"
              ? {
                  framework: t.framework,
                  files: t.files,
                  visibleFiles: t.visibleFiles,
                  activeFile: t.activeFile,
                  tests: t.tests,
                  testCount: countTests(t.tests),
                  dependencies: t.dependencies,
                }
              : null;
          return `  (${q(t.slug)}, ${q(t.kind)}, ${t.complexity}, ${t.estSeconds}, ${j(t.title)}, ${j(t.prompt)}, ${q(lecture)}, ${j(quiz)}, ${j(practice)})`;
        })
        .join(",\n"),
    );
    out.push(") as v(slug, kind, complexity, est_seconds, title, prompt, lecture_slug, quiz, practice)");
    out.push("left join public.lectures l on l.slug = v.lecture_slug");
    out.push(
      "on conflict (slug) do update set kind = excluded.kind, complexity = excluded.complexity, est_seconds = excluded.est_seconds,",
      "  title = excluded.title, prompt = excluded.prompt, lecture_id = excluded.lecture_id, quiz = excluded.quiz,",
      "  practice = excluded.practice, published = true, updated_at = now()",
      "where cur.source = 'seed';",
      "",
    );

    // Unpublish tasks that were removed from the content folder (keeps history intact).
    out.push(`update public.tasks set published = false where source = 'seed' and slug not in (${allTaskSlugs.map(q).join(", ")});`, "");

    // Task ↔ skill links
    out.push(`delete from public.task_skills where task_id in (select id from public.tasks where source = 'seed' and slug in (${tasks.map((t) => q(t.slug)).join(", ")}));`);
    out.push("insert into public.task_skills (task_id, skill_id, weight)");
    out.push("select t.id, s.id, v.weight from (values");
    out.push(
      tasks
        .flatMap((t) =>
          t.skills.map((ref) => {
            const slug = typeof ref === "string" ? ref : ref.slug;
            const weight = typeof ref === "string" ? 1 : ref.weight;
            return `  (${q(t.slug)}, ${q(slug)}, ${weight}::real)`;
          }),
        )
        .join(",\n"),
    );
    out.push(") as v(task_slug, skill_slug, weight)");
    out.push("join public.tasks t on t.slug = v.task_slug and t.source = 'seed'");
    out.push("join public.skills s on s.slug = v.skill_slug", "on conflict do nothing;", "");

    // Solutions (private schema)
    out.push("insert into private.task_solutions (task_id, correct_option_ids, explanation, solution_files)");
    out.push("select t.id, v.correct_option_ids, v.explanation, v.solution_files from (values");
    out.push(
      tasks
        .map((t) => {
          const correct = t.kind === "quiz" ? arr(t.correct) : "null::text[]";
          const files = t.kind === "practice" ? j(t.solution) : "null::jsonb";
          return `  (${q(t.slug)}, ${correct}, ${j(t.explanation)}, ${files})`;
        })
        .join(",\n"),
    );
    out.push(") as v(task_slug, correct_option_ids, explanation, solution_files)");
    out.push("join public.tasks t on t.slug = v.task_slug and t.source = 'seed'");
    out.push(
      "on conflict (task_id) do update set correct_option_ids = excluded.correct_option_ids,",
      "  explanation = excluded.explanation, solution_files = excluded.solution_files;",
      "",
    );
  }

  // Courses: catalogue rows, modules, slides and the private answer keys.
  out.push("insert into public.courses as cur (slug, title, summary, topics, sort_order) values");
  out.push(
    catalogCourses.map((c, i) => `  (${q(c.slug)}, ${j(c.title)}, ${j(c.summary)}, ${j(c.topics)}, ${i + 1})`).join(",\n"),
  );
  // Course rows edited in the admin panel (source = 'admin') are never overwritten or deleted by the seed.
  out.push(
    "on conflict (slug) do update set title = excluded.title, summary = excluded.summary, topics = excluded.topics,",
    "  sort_order = excluded.sort_order, updated_at = now()",
    "where cur.source = 'seed';",
    "",
  );

  for (const { course, modules } of loadedCourses) {
    const slides = modules.flatMap((m) => m.slides.map((s) => ({ ...s, moduleSlug: m.slug })));
    out.push(
      `delete from public.course_slides s using public.courses c where s.course_id = c.id and c.slug = ${q(course)} and s.source = 'seed' and s.slug not in (${slides.map((s) => q(s.slug)).join(", ")});`,
      "",
      `delete from public.course_modules m using public.courses c where m.course_id = c.id and c.slug = ${q(course)} and m.source = 'seed' and m.slug not in (${modules.map((m) => q(m.slug)).join(", ")}) and not exists (select 1 from public.course_slides x where x.module_id = m.id and x.source = 'admin');`,
      "",
    );

    out.push("insert into public.course_modules as cur (course_id, slug, title, sort_order)");
    out.push("select c.id, v.slug, v.title, v.sort_order from (values");
    out.push(modules.map((m, i) => `  (${q(course)}, ${q(m.slug)}, ${j(m.title)}, ${i + 1})`).join(",\n"));
    out.push(") as v(course_slug, slug, title, sort_order)");
    out.push("join public.courses c on c.slug = v.course_slug");
    out.push("on conflict (course_id, slug) do update set title = excluded.title, sort_order = excluded.sort_order", "where cur.source = 'seed';", "");

    out.push("insert into public.course_slides as cur (course_id, module_id, slug, kind, title, body, quiz, practice, max_score, sort_order, updated_at)");
    out.push("select m.course_id, m.id, v.slug, v.kind, v.title, v.body, v.quiz, v.practice, v.max_score, v.sort_order, now() from (values");
    out.push(
      slides
        .map((s, i) => {
          const quiz =
            s.kind === "quiz"
              ? { questions: s.questions.map(({ correct: _correct, ...publicPart }) => publicPart) }
              : null;
          const practice =
            s.kind === "practice" ? { language: s.language, starter: s.starter, ...(s.setup ? { setup: s.setup } : {}) } : null;
          return `  (${q(course)}, ${q(s.moduleSlug)}, ${q(s.slug)}, ${q(s.kind)}, ${j(s.title)}, ${j(s.body)}, ${j(quiz)}, ${j(practice)}, ${s.maxScore}, ${i + 1})`;
        })
        .join(",\n"),
    );
    out.push(") as v(course_slug, module_slug, slug, kind, title, body, quiz, practice, max_score, sort_order)");
    out.push("join public.courses c on c.slug = v.course_slug");
    out.push("join public.course_modules m on m.course_id = c.id and m.slug = v.module_slug");
    out.push(
      "on conflict (course_id, slug) do update set module_id = excluded.module_id, kind = excluded.kind, title = excluded.title,",
      "  body = excluded.body, quiz = excluded.quiz, practice = excluded.practice, max_score = excluded.max_score,",
      "  sort_order = excluded.sort_order, updated_at = now()",
      "where cur.source = 'seed';",
      "",
    );

    const keyed = slides.filter((s) => s.kind !== "lecture");
    if (keyed.length) {
      out.push("insert into private.course_slide_keys (slide_id, quiz_answers, expected_output, solution)");
      out.push("select s.id, v.quiz_answers, v.expected_output, v.solution from (values");
      out.push(
        keyed
          .map((s) => {
            const answers = s.kind === "quiz" ? Object.fromEntries(s.questions.map((qq) => [qq.id, qq.correct])) : null;
            const expected = s.kind === "practice" ? s.expectedOutput : null;
            const solution = s.kind === "practice" ? s.solution : null;
            return `  (${q(course)}, ${q(s.slug)}, ${j(answers)}, ${text(expected)}, ${text(solution)})`;
          })
          .join(",\n"),
      );
      out.push(") as v(course_slug, slide_slug, quiz_answers, expected_output, solution)");
      out.push("join public.courses c on c.slug = v.course_slug");
      out.push("join public.course_slides s on s.course_id = c.id and s.slug = v.slide_slug and s.source = 'seed'");
      out.push(
        "on conflict (slide_id) do update set quiz_answers = excluded.quiz_answers, expected_output = excluded.expected_output,",
        "  solution = excluded.solution;",
        "",
      );
    }
  }

  if (courseTasks.length) out.push(...courseTaskSql(courseTasks, lectures), "");

  // has_content also counts tasks created in the admin panel. Runs last, after every task insert.
  out.push(
    "update public.skills s set has_content = exists (",
    "  select 1 from public.task_skills ts join public.tasks t on t.id = ts.task_id and t.published where ts.skill_id = s.id);",
    "",
  );

  out.push("commit;", "");
  writeFileSync("supabase/seed.sql", out.join("\n"));

  const quizzes = tasks.filter((t) => t.kind === "quiz").length;
  const courseQuizzes = courseTasks.filter((t) => t.kind === "quiz").length;
  console.log(
    `seed.sql written: ${skills.length} skills, ${lectures.length} lectures, ${quizzes} quizzes, ${tasks.length - quizzes} practice tasks, ` +
      `plus ${courseQuizzes} quizzes and ${courseTasks.length - courseQuizzes} practice tasks from courses.`,
  );
}

/**
 * Interview tasks copied from course slides (content/course-tasks.ts): the same rows the admin import
 * makes, linked to their slide. Runs after the course slides exist. A slide question an admin already
 * copied by hand keeps that copy (the unique index on copied_from_* allows only one).
 */
function courseTaskSql(courseTasks: CourseTask[], lectures: { slug: string; skill: string }[]): string[] {
  const out: string[] = [];
  const lectureOf = (t: CourseTask) => lectures.find((l) => l.skill === refSlug(t.skills[0]))?.slug ?? null;
  const slugList = courseTasks.map((t) => q(t.slug)).join(", ");

  out.push(
    "insert into public.tasks as cur (slug, kind, complexity, est_seconds, title, prompt, lecture_id, quiz, practice, published, copied_from_slide_id, copied_from_question, updated_at)",
    "select v.slug, v.kind::public.task_kind, v.complexity, v.est_seconds, v.title, v.prompt, l.id, v.quiz, v.practice, true, s.id, v.question, now() from (values",
    courseTasks
      .map((t) => {
        const quiz = t.kind === "quiz" ? t.quiz : null;
        const practice = t.kind === "practice" ? t.practice : null;
        return `  (${q(t.slug)}, ${q(t.kind)}, ${t.complexity}, ${t.estSeconds}, ${j(t.title)}, ${j(t.prompt)}, ${q(lectureOf(t))}::text, ${j(quiz)}, ${j(practice)}, ${q(t.course)}, ${q(t.slide)}, ${q(t.question)}::text)`;
      })
      .join(",\n"),
    ") as v(slug, kind, complexity, est_seconds, title, prompt, lecture_slug, quiz, practice, course_slug, slide_slug, question)",
    "join public.courses c on c.slug = v.course_slug",
    "join public.course_slides s on s.course_id = c.id and s.slug = v.slide_slug",
    "left join public.lectures l on l.slug = v.lecture_slug",
    "where not exists (select 1 from public.tasks x where x.copied_from_slide_id = s.id",
    "  and coalesce(x.copied_from_question, '') = coalesce(v.question, '') and x.slug <> v.slug)",
    "on conflict (slug) do update set kind = excluded.kind, complexity = excluded.complexity, est_seconds = excluded.est_seconds,",
    "  title = excluded.title, prompt = excluded.prompt, lecture_id = excluded.lecture_id, quiz = excluded.quiz,",
    "  practice = excluded.practice, published = true, copied_from_slide_id = excluded.copied_from_slide_id,",
    "  copied_from_question = excluded.copied_from_question, updated_at = now()",
    "where cur.source = 'seed';",
    "",
  );

  out.push(
    `delete from public.task_skills where task_id in (select id from public.tasks where source = 'seed' and slug in (${slugList}));`,
    "insert into public.task_skills (task_id, skill_id, weight)",
    "select t.id, s.id, v.weight from (values",
    courseTasks
      .flatMap((t) => t.skills.map((ref) => `  (${q(t.slug)}, ${q(refSlug(ref))}, ${typeof ref === "string" ? 1 : ref.weight}::real)`))
      .join(",\n"),
    ") as v(task_slug, skill_slug, weight)",
    "join public.tasks t on t.slug = v.task_slug and t.source = 'seed'",
    "join public.skills s on s.slug = v.skill_slug",
    "on conflict do nothing;",
    "",
  );

  out.push(
    "insert into private.task_solutions (task_id, correct_option_ids, explanation, solution_files, expected_output)",
    "select t.id, v.correct_option_ids, v.explanation, v.solution_files, v.expected_output from (values",
    courseTasks
      .map((t) => {
        const correct = t.kind === "quiz" ? arr(t.correct) : "null::text[]";
        const files = t.kind === "practice" ? j(t.solution) : "null::jsonb";
        const expected = t.kind === "practice" ? text(t.expectedOutput) : "null::text";
        return `  (${q(t.slug)}, ${correct}, ${j(t.explanation)}, ${files}, ${expected})`;
      })
      .join(",\n"),
    ") as v(task_slug, correct_option_ids, explanation, solution_files, expected_output)",
    "join public.tasks t on t.slug = v.task_slug and t.source = 'seed'",
    "on conflict (task_id) do update set correct_option_ids = excluded.correct_option_ids,",
    "  explanation = excluded.explanation, solution_files = excluded.solution_files, expected_output = excluded.expected_output;",
  );
  return out;
}

main();
